#!/usr/bin/env python3
"""Rust Bullet raw FP32 -> quantized picoAlpha PANNI8 (C++, ARM) + .hpp.

Bullet matrices stored column-major, so 64x16 heads are transposed to
picoAlpha's row-major 64x16. There are no biases anywhere in this architecture.
"""
import argparse,csv,hashlib,json,math,struct
from pathlib import Path

INPUTS,H=780,16
SHAPES=(('W_INPUT',780,16),('W_VALUE',1,16),('W_FROM',64,16),('W_TO',64,16))
LENGTHS=[rows*cols for _,rows,cols in SHAPES]
TOTAL=sum(LENGTHS)
MAGIC=b'PANNI8\r\n'
SIZE=14580

def load_raw(path):
    raw=Path(path).read_bytes()
    if len(raw)!=TOTAL*4:raise ValueError(f'Unexpected checkpoint raw.bin size: {len(raw)} (expected {TOTAL*4})')
    floats=struct.unpack('<%df'%TOTAL,raw)
    if not all(math.isfinite(x) for x in floats):raise ValueError('Non-finite FP32 in raw.bin')
    return floats

def transpose_bullet(values,rows,cols):
    return [values[j*rows+i] for i in range(rows) for j in range(cols)]

def f32(x):return struct.unpack('<f',struct.pack('<f',x))[0]

def quantize(floats):
    mats={};scales={};off=0
    for name,rows,cols in SHAPES:
        vals=(transpose_bullet(floats[off:off+rows*cols],rows,cols) if name in ('W_FROM','W_TO') else list(floats[off:off+rows*cols]))
        scale=max(f32(max(abs(v) for v in vals)/127.0),f32(1e-12))
        # Python round matches Rust f32::round for normal non-half values.
        q=[max(-127,min(127,math.floor(f32(v/scale)+0.5) if v>=0 else math.ceil(f32(v/scale)-0.5))) for v in vals]
        mats[name]=q;scales[name]=scale;off+=rows*cols
    return mats,scales

def encode(mats,scales):
    data=bytearray(MAGIC+struct.pack('<III',1,INPUTS,H))
    for name,_,_ in SHAPES:data+=struct.pack('<f',scales[name])
    for name,rows,cols in SHAPES:
        vals=mats[name]
        if len(vals)!=rows*cols or any(not -127<=v<=127 for v in vals):raise ValueError(f'Invalid {name}')
        data+=struct.pack('<%db'%len(vals),*vals)
    assert len(data)==SIZE
    return bytes(data)

def decode(data):
    if len(data)!=SIZE or data[:8]!=MAGIC:raise ValueError('Invalid PANNI8 size/magic')
    ver,inp,hidden=struct.unpack_from('<III',data,8)
    if (ver,inp,hidden)!=(1,INPUTS,H):raise ValueError('Wrong version/architecture')
    scales=dict(zip((k for k,_,_ in SHAPES),struct.unpack_from('<4f',data,20)))
    if any(not math.isfinite(x) or x<=0 for x in scales.values()):raise ValueError('Invalid scales')
    matrices={};at=36
    for name,rows,cols in SHAPES:
        matrices[name]=list(struct.unpack_from('<%db'%(rows*cols),data,at));at+=rows*cols
    return matrices,scales

def write_hpp(path,mats,scales):
    lines=['// Generated by Bullet MCTS Genesis, picoAlpha-compatible INT8 weights.','#pragma once','#include <stdint.h>','namespace picoalpha_nnue {','constexpr int INPUTS = 780;','constexpr int HIDDEN = 16;']
    for name,_,_ in SHAPES:
        s=struct.unpack('<f',struct.pack('<f',scales[name]))[0]
        lines.append(f'constexpr float {name}_SCALE = {s:.9g}f;')
        a=mats[name];lines.append(f'alignas(4) static const int8_t {name}[{len(a)}] = {{')
        for j in range(0,len(a),24):lines.append('  '+', '.join(str(v) for v in a[j:j+24])+',')
        lines.append('};')
    lines+=['} // namespace picoalpha_nnue','']
    Path(path).write_text('\n'.join(lines))

def select(csvpath):
    with open(csvpath,newline='') as f:rows=list(csv.DictReader(f))
    rows=[r for r in rows if r['model'].isdigit()]
    if not rows:raise ValueError('No validated models')
    return min(rows,key=lambda r:float(r['objective']))

def main():
    p=argparse.ArgumentParser();p.add_argument('--csv',required=True);p.add_argument('--checkpoints',required=True)
    p.add_argument('--id',required=True);p.add_argument('--out',required=True)
    a=p.parse_args();best=select(a.csv)
    source=Path(a.checkpoints)/f"{a.id}-{best['model']}"/'raw.bin'
    raw=load_raw(source)
    matrices,scales=quantize(raw)
    dest=Path(a.out);dest.mkdir(parents=True,exist_ok=True)
    data=encode(matrices,scales)
    (dest/'best_int8.bin').write_bytes(data)
    write_hpp(dest/'picoalpha_nnue_weights.hpp',matrices,scales)
    # Lossless quantized matrices in a language-neutral description (not PyTorch).
    checkpoint={'format':'picoalpha-nnue-int8-v1','source':'Bullet Rust/Metal','config':{'features':780,'hidden':16,'policy':'from_to','value':'tanh'},
      'matrices':matrices,'scales':scales,'checkpoint':int(best['model'])}
    (dest/'best_int8.json').write_text(json.dumps(checkpoint,separators=(',',':')))
    dm,ds=decode(data)
    if dm!=matrices:raise AssertionError('Binary roundtrip mismatch')
    result={'source_checkpoint':str(source),'best_superbatch':int(best['model']),'selection':'min val objective after INT8 quantization',
      'validation':best,'format':'PANNI8','bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),'input':780,'hidden':16,
      'weights':14544,'warning':'Not a Nurse .pt checkpoint: Nurse MCTSE currently loads .pt; use binary C++/ARM or adapt Nurse.'}
    (dest/'report.json').write_text(json.dumps(result,indent=2,ensure_ascii=False))
    print(f"EXPORTED {dest/'best_int8.bin'} size={len(data)} SB={best['model']} objective={best['objective']}")

if __name__=='__main__':main()

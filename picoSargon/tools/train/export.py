"""Export QAT checkpoint as exact GRMP0001 and constexpr embedded bytes."""
import argparse
import re
import sys
from pathlib import Path
import numpy as np
from network import read_binary, write_binary, N_CODES
from train import Progress


def main():
    p=argparse.ArgumentParser(description='Export trained 6-bit weights to GRMP0001 + C++ header')
    p.add_argument('--in',dest='source',required=True,help='train.py checkpoint *_best.pt or *_epoch_XXXX.pt')
    p.add_argument('--bin',required=True,help='GRMP0001 binary output path')
    p.add_argument('--include',required=True,help='C++ header output path')
    p.add_argument('--symbol',default='pitty_network',help='C++ byte array symbol')
    a=p.parse_args()
    if not re.fullmatch('[A-Za-z_][A-Za-z0-9_]*',a.symbol):p.error('invalid C++ symbol')
    progress=Progress('EXPORT',4)
    progress.update(0,force=True)
    import torch
    try: checkpoint=torch.load(a.source,map_location='cpu',weights_only=True)
    except TypeError:checkpoint=torch.load(a.source,map_location='cpu')
    if checkpoint.get('version') != 2 or checkpoint.get('selection_metric') != 'mse_value':
        raise RuntimeError('Checkpoint does not satisfy FP32/QAT v2 MSE(value) contract')
    if not checkpoint.get('stats',{}).get('quantized_exact'):
        raise RuntimeError('Checkpoint has no exact quantized validation metrics')
    w=checkpoint['weights'].detach().cpu().numpy()
    # Identical to train.py QAT forward; no new scale or int8 conversion.
    progress.update(1)
    quant=np.rint(np.clip(w,-31,32)).astype(np.int16)
    clipped=int(np.sum((w < -31)|(w > 32)))
    blob=write_binary(a.bin,quant)
    progress.update(2)
    assert np.array_equal(read_binary(a.bin),quant)
    dst=Path(a.include);dst.parent.mkdir(parents=True,exist_ok=True)
    values=',\n'.join('  '+', '.join(f'0x{b:02x}' for b in blob[i:i+16]) for i in range(0,len(blob),16))
    progress.update(3)
    dst.write_text(f'''// Generated by picoSargon/tools/train/export.py. GRMP0001, {len(blob)} bytes.
#pragma once
#include <cstddef>
#include <cstdint>
namespace picoSargon {{
inline constexpr std::uint8_t {a.symbol}[] = {{
{values}
}};
inline constexpr std::size_t {a.symbol}_size = sizeof({a.symbol});
}} // namespace picoSargon
''',encoding='utf-8')
    progress.update(4)
    print(f'⚙️ Export checkpoint={a.source} epoch={checkpoint.get("epoch")}')
    print(f'📊 1680 signed 6-bit coefficients; header=44 bytes; payload=1260 bytes; total={len(blob)} bytes')
    print(f'📊 quantized range=[{quant.min()},{quant.max()}], negative={int(np.sum(quant<0))}, zero={int(np.sum(quant==0))}, saturated={clipped}')
    print(f'✅ BIN {a.bin}: {Path(a.bin).stat().st_size} bytes')
    print(f'✅ INCLUDE {a.include}: {dst.stat().st_size} bytes')
    print('✅ Read-back SHA256 and coefficient equality verified')

if __name__=='__main__':
    try:main()
    except Exception as exc:
        print(f'❌ {type(exc).__name__}: {exc}',file=sys.stderr)
        raise

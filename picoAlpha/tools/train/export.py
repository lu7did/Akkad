"""Export ONE quantized INT8 weight set to both C++ header and PyTorch .pt.

Integer reference inference: hq = relu(sum(q_input[active_features]));
logit = dot(q_head[row], hq) * input_scale * head_scale.
Only weight storage is INT8; accumulators are INT32 and output scales FP32.
"""
import argparse
import os
import re
import torch

SHAPES = {'W_INPUT': (780,16), 'W_VALUE': (1,16), 'W_FROM': (64,16), 'W_TO': (64,16)}
STATE_KEYS = {'W_INPUT':'embed.weight','W_VALUE':'value.weight',
              'W_FROM':'from_head.weight','W_TO':'to_head.weight'}


def quantize(checkpoint):
    conf = checkpoint.get('config', {})
    if (conf.get('features'),conf.get('hidden')) != (780,16):
        raise ValueError('Checkpoint architecture must be 780x16')
    if conf.get('policy','from_to') != 'from_to' or conf.get('value','tanh') != 'tanh':
        raise ValueError('Checkpoint policy/value format incompatible')
    state=checkpoint['state_dict']
    if set(state) != set(STATE_KEYS.values()):
        raise ValueError('Unexpected checkpoint tensors')
    matrices={};scales={}
    for name,key in STATE_KEYS.items():
        x=state[key].detach().cpu().float().contiguous()
        if tuple(x.shape) != SHAPES[name] or not bool(torch.isfinite(x).all()):
            raise ValueError('Invalid weight shape or nonfinite value: '+name)
        scale=max(float(x.abs().max())/127.0,1e-12)
        matrices[name]=torch.clamp(torch.round(x/scale),-127,127).to(torch.int8).contiguous()
        scales[name]=scale
    return {'format':'picoalpha-nnue-int8-v1',
            'config':{'features':780,'hidden':16,'policy':'from_to','value':'tanh','quantization':'symmetric_int8_per_matrix'},
            'weights':matrices,'scales':scales}


def write_header(path,namespace,network):
    lines=['// Generated by picoAlpha/tools/train/export.py. Same quantized weights as .pt output.',
           '// Sparse sum INT8 input rows into INT32; ReLU on integer accumulator.',
           '// Head dot product INT32; multiply by W_INPUT_SCALE * respective head SCALE.',
           '// Value head: tanh(scaled dot); legal move logits: FROM[src] + TO[dst].',
           '#pragma once','#include <stdint.h>',f'namespace {namespace} {{',
           'constexpr int INPUTS = 780;', 'constexpr int HIDDEN = 16;']
    for name in SHAPES:
        tensor=network['weights'][name]
        vals=tensor.view(-1).tolist()
        lines.append(f'constexpr float {name}_SCALE = {network["scales"][name]:.17g}f;')
        lines.append(f'alignas(4) static const int8_t {name}[{len(vals)}] = {{')
        for i in range(0,len(vals),24):lines.append('  '+', '.join(map(str,vals[i:i+24]))+',')
        lines.append('};')
    lines.append(f'}} // namespace {namespace}')
    os.makedirs(os.path.dirname(os.path.abspath(path)),exist_ok=True)
    with open(path,'w',encoding='ascii') as f:f.write('\n'.join(lines)+'\n')


def main():
    p=argparse.ArgumentParser(description='Export identical INT8 weights as C++ header and PyTorch checkpoint')
    p.add_argument('--in',dest='source',required=True,help='FP32 training checkpoint .pt')
    p.add_argument('--out',required=True,help='C++ header .h/.hpp')
    p.add_argument('--int8',required=True,help='Mandatory quantized PyTorch .pt output')
    p.add_argument('--namespace',default='picoalpha_nnue')
    a=p.parse_args()
    if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',a.namespace):p.error('Invalid C++ namespace')
    src=os.path.abspath(a.source);hdr=os.path.abspath(a.out);pt=os.path.abspath(a.int8)
    if len({src,hdr,pt})!=3:p.error('Input, C++ header and INT8 checkpoint must be distinct files')
    if not hdr.lower().endswith(('.h','.hpp')) or not pt.lower().endswith('.pt'):
        p.error('Expected C++ .h/.hpp and quantized .pt destinations')
    ck=torch.load(src,map_location='cpu',weights_only=True)
    network=quantize(ck)
    # Serialize .pt first, then header, both derived from exactly the same object.
    os.makedirs(os.path.dirname(pt),exist_ok=True)
    torch.save(network,pt)
    write_header(hdr,a.namespace,network)
    print(f'INT8 weights={sum(t.numel() for t in network["weights"].values())} bytes')
    print(f'C++ header: {hdr}')
    print(f'PyTorch INT8: {pt} (int8 tensors; int32 accumulators; float output scales)')

if __name__=='__main__':main()
